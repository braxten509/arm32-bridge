#!/usr/bin/env python3
"""Generates C source for a 64-bit stand-in of a helper 32-bit library.

The stand-in's JNI_OnLoad registers "do nothing" implementations (returning
0 / false / null) for every native Java method of the classes the original
library names in its strings, so Java code that calls them keeps working
with that feature (crash reporting, ads, ...) simply switched off.

usage: tools/gen_stub_lib.py <dexdump.txt> <lib32.so> <output.c>
"""
import re
import subprocess
import sys

DEXDUMP, LIBRARY, OUTPUT = sys.argv[1], sys.argv[2], sys.argv[3]

strings = set(subprocess.run(["strings", "-n", "6", LIBRARY], capture_output=True, text=True).stdout.split())
natives = {}
current_class = name = signature = None
for line in open(DEXDUMP, errors="replace"):
    line = line.strip()
    m = re.match(r"#\d+\s+: \(in L(.+);\)", line)
    if m:
        current_class = m.group(1)
        continue
    m = re.match(r"name\s+: '(.*)'", line)
    if m:
        name = m.group(1)
        continue
    m = re.match(r"type\s+: '(.*)'", line)
    if m:
        signature = m.group(1)
        continue
    if line.startswith("access") and "NATIVE" in line and current_class in strings:
        natives.setdefault(current_class, []).append((name, signature))

out = ["// Generated by tools/gen_stub_lib.py. Do not edit.", "#include <jni.h>", "",
       "static jlong zero_word(void) { return 0; }",
       "static jfloat zero_float(void) { return 0; }",
       "static jdouble zero_double(void) { return 0; }", ""]
for index, (cls, methods) in enumerate(sorted(natives.items())):
    out.append(f"static const JNINativeMethod methods{index}[] = {{")
    for method, signature in methods:
        returned = signature[signature.index(")") + 1]
        function = {"F": "zero_float", "D": "zero_double"}.get(returned, "zero_word")
        out.append(f'    {{"{method}", "{signature}", (void *){function}}},')
    out.append("};")
out += ["", "JNIEXPORT jint JNI_OnLoad(JavaVM *vm, void *reserved) {", "    JNIEnv *env;",
        "    if ((*vm)->GetEnv(vm, (void **)&env, JNI_VERSION_1_6) != JNI_OK) return -1;", "    jclass c;"]
for index, (cls, methods) in enumerate(sorted(natives.items())):
    out.append(f'    c = (*env)->FindClass(env, "{cls}");')
    out.append(f"    if (c) (*env)->RegisterNatives(env, c, methods{index}, {len(methods)});")
    out.append("    (*env)->ExceptionClear(env);")
out += ["    return JNI_VERSION_1_6;", "}", ""]
open(OUTPUT, "w").write("\n".join(out))
print(f"stand-in registers {sum(len(m) for m in natives.values())} methods in {len(natives)} classes", file=sys.stderr)
