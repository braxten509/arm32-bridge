#!/usr/bin/env python3
"""Generates the 64-bit Java_* entry points that forward into a 32-bit library.

Inputs: `dexdump` output for the app's classes*.dex (to learn each native
method's Java signature) and the 32-bit library (to learn which Java_*
functions it really exports). Output: Rust source with one
`#[no_mangle] extern "system" fn Java_...` per native method the library
implements, each calling `app::forward` with typed arguments.

usage: tools/gen_exports.py <dexdump.txt> <lib32.so> <output.rs>
"""
import re
import subprocess
import sys

DEXDUMP, LIBRARY, OUTPUT = sys.argv[1], sys.argv[2], sys.argv[3]


def mangle(text):
    out = []
    for c in text:
        if c == "/":
            out.append("_")
        elif c == "_":
            out.append("_1")
        elif c == ";":
            out.append("_2")
        elif c == "[":
            out.append("_3")
        elif c.isalnum() and ord(c) < 128:
            out.append(c)
        else:
            out.append("_0%04x" % ord(c))
    return "".join(out)


def parameters(signature):
    inside = signature[1:signature.index(")")]
    result, i = [], 0
    while i < len(inside):
        start = i
        while inside[i] == "[":
            i += 1
        if inside[i] == "L":
            i = inside.index(";", i)
        i += 1
        kind = inside[start]
        result.append("L" if kind in "L[" else kind)
    returned = signature[signature.index(")") + 1:]
    return result, ("L" if returned[0] in "L[" else returned[0])


natives = []
current_class = name = signature = None
for line in open(DEXDUMP, errors="replace"):
    line = line.strip()
    m = re.match(r"#\d+\s+: \(in L(.+);\)", line)
    if m:
        current_class = m.group(1)
        continue
    m = re.match(r"name\s+: '(.*)'", line)
    if m:
        name = m.group(1)
        continue
    m = re.match(r"type\s+: '(.*)'", line)
    if m:
        signature = m.group(1)
        continue
    if line.startswith("access") and "NATIVE" in line and current_class and name and signature.startswith("("):
        natives.append((current_class, name, signature))

symbols = subprocess.run(["readelf", "--dyn-syms", "-W", LIBRARY], capture_output=True, text=True).stdout
exported = set()
for row in symbols.splitlines():
    parts = row.split()
    if len(parts) >= 8 and parts[6] != "UND" and parts[7].startswith("Java_"):
        exported.add(parts[7].split("@")[0])

RUST = {"Z": "jboolean", "B": "jbyte", "C": "jchar", "S": "jshort", "I": "jint", "J": "jlong",
        "F": "jfloat", "D": "jdouble", "L": "jobject", "V": None}
ARG = {"Z": "Int({} as i32)", "B": "Int({} as i32)", "C": "Int({} as i32)", "S": "Int({} as i32)",
       "I": "Int({})", "J": "Long({})", "F": "Float({})", "D": "Double({})", "L": "Object({})"}
CONVERT = {"Z": ".int() as jboolean", "B": ".int() as jbyte", "C": ".int() as jchar", "S": ".int() as jshort",
           "I": ".int()", "J": ".long()", "F": ".float()", "D": ".double()", "L": ".object()", "V": ";"}

functions, seen = [], set()
for cls, method, signature in natives:
    short = "Java_" + mangle(cls) + "_" + mangle(method)
    long = short + "__" + mangle(signature[1:signature.index(")")])
    symbol = short if short in exported else long if long in exported else None
    if symbol is None or symbol in seen:
        continue
    seen.add(symbol)
    params, returned = parameters(signature)
    names = [f"p{i}" for i in range(len(params))]
    decl = ", ".join(f"{n}: {RUST[k]}" for n, k in zip(names, params))
    args = ", ".join(["HostArg::Object(this)"] + ["HostArg::" + ARG[k].format(n) for n, k in zip(names, params)])
    ret = f" -> {RUST[returned]}" if RUST[returned] else ""
    tail = CONVERT[returned]
    functions.append(
        f"#[no_mangle]\npub unsafe extern \"system\" fn {symbol}(env: *mut JNIEnv, this: jobject"
        + (f", {decl}" if decl else "") + f"){ret} {{\n"
        f"    static ADDRESS: AtomicU32 = AtomicU32::new(0);\n"
        f"    forward(env, \"{symbol}\", &ADDRESS, &[{args}], b'{returned}'){tail}\n}}\n"
    )

missing = sorted(exported - seen)
with open(OUTPUT, "w") as out:
    out.write("// Generated by tools/gen_exports.py. Do not edit.\n")
    out.write(f"// {len(functions)} entry points; exported but without a Java declaration: {len(missing)}\n\n")
    out.write("\n".join(functions))
print(f"generated {len(functions)} entry points; {len(missing)} exports had no native declaration", file=sys.stderr)
for symbol in missing:
    print(f"  no declaration: {symbol}", file=sys.stderr)
