#!/usr/bin/env python3
"""Generates src/imports/gles_generated.rs from the NDK's OpenGL ES 1 and 2 headers.

Every prototype becomes a handler that reads the 32-bit caller's arguments,
turns guest pointers into host pointers, and calls the real (64-bit) GL
function, looked up at run time. Functions needing special treatment are
listed in SPECIAL and written by hand in src/imports/gles.rs.

usage: tools/gen_gles.py <ndk sysroot include dir> <output.rs>
"""
import re
import sys

INCLUDE, OUTPUT = sys.argv[1], sys.argv[2]

# GLES2 extension functions worth bridging (core GLES2, core GLES1 and every
# GLES1 OES extension are always included).
EXTENSIONS = {
    "glGenVertexArraysOES", "glBindVertexArrayOES", "glDeleteVertexArraysOES", "glIsVertexArrayOES",
    "glDiscardFramebufferEXT",
}
# Hand-written in gles.rs.
SPECIAL = {
    "glVertexAttribPointer", "glDrawElements", "glShaderSource", "glGetString", "glMapBufferOES",
    "glUnmapBufferOES", "glBindBuffer", "glBindVertexArrayOES", "glDeleteBuffers", "glDeleteVertexArraysOES",
    "glGetVertexAttribPointerv", "glGetBufferPointervOES",
    "glVertexPointer", "glColorPointer", "glTexCoordPointer", "glNormalPointer", "glPointSizePointerOES",
    "glMatrixIndexPointerOES", "glWeightPointerOES", "glGetPointerv",
}

INTEGER = {
    "GLenum": ("u32", "a.u32()"), "GLuint": ("u32", "a.u32()"), "GLbitfield": ("u32", "a.u32()"),
    "GLint": ("i32", "a.i32()"), "GLclampx": ("i32", "a.i32()"), "GLsizei": ("i32", "a.i32()"), "GLfixed": ("i32", "a.i32()"),
    "GLboolean": ("u8", "a.u32() as u8"), "GLubyte": ("u8", "a.u32() as u8"),
    "GLshort": ("i16", "a.u32() as i16"), "GLushort": ("u16", "a.u32() as u16"),
    "GLfloat": ("f32", "a.f32()"), "GLclampf": ("f32", "a.f32()"),
    "GLintptr": ("isize", "a.i32() as isize"), "GLsizeiptr": ("isize", "a.i32() as isize"),
    "GLint64": ("i64", "a.i64()"), "GLuint64": ("u64", "a.u64()"),
}
RETURNS = {"void": None, "GLenum": "u32", "GLuint": "u32", "GLint": "i32", "GLboolean": "u8", "GLbitfield": "u32"}

prototype = re.compile(r"GL_API(?:CALL)?\s+(.+?)\s*GL_APIENTRY\s+(\w+)\s*\((.*?)\);", re.S)


def parse(path, only=None):
    text = open(path).read()
    for match in prototype.finditer(text):
        result, name, parameters = match.group(1).strip(), match.group(2), match.group(3).strip()
        if only is not None and name not in only:
            continue
        yield result, name, parameters


def convert(result, name, parameters):
    if result not in RETURNS:
        return None
    params = [] if parameters in ("", "void") else [p.strip() for p in parameters.split(",")]
    rust_types, reads = [], []
    for i, param in enumerate(params):
        if "*" in param:
            rust_types.append("*mut c_void")
            reads.append(f"guest_pointer(a.u32())")
            continue
        words = param.replace("const ", "").split()
        kind = words[0]
        if kind not in INTEGER:
            return None
        rust_types.append(INTEGER[kind][0])
        reads.append(INTEGER[kind][1])
    returned = RETURNS[result]
    signature = f"unsafe extern \"C\" fn({', '.join(rust_types)})" + (f" -> {returned}" if returned else "")
    lets = "".join(f"let p{i} = {read}; " for i, read in enumerate(reads))
    call = f"function({', '.join(f'p{i}' for i in range(len(reads)))})"
    body = (
        f"{lets}static ADDRESS: AtomicUsize = AtomicUsize::new(0); "
        f"let function: {signature} = unsafe {{ std::mem::transmute(host_function(&ADDRESS, \"{name}\")) }}; "
    )
    if returned is None:
        body += f"unsafe {{ {call} }}; Ret::Void"
    else:
        body += f"Ret::U32(unsafe {{ {call} }} as u32)"
    return f"        \"{name}\" => handler!(|uc, a| {{ {body} }}),"


lines = []
names = []
sources = (
    list(parse(f"{INCLUDE}/GLES2/gl2.h"))
    + list(parse(f"{INCLUDE}/GLES2/gl2ext.h", EXTENSIONS))
    + list(parse(f"{INCLUDE}/GLES/gl.h"))
    + list(parse(f"{INCLUDE}/GLES/glext.h"))
)
for result, name, parameters in sources:
    if name in SPECIAL or name in names:
        continue
    arm = convert(result, name, parameters)
    if arm is None:
        print(f"skipped {name}: unsupported types", file=sys.stderr)
        continue
    lines.append(arm)
    names.append(name)

with open(OUTPUT, "w") as out:
    out.write("// Generated by tools/gen_gles.py from the NDK's GLES1 and GLES2 headers. Do not edit.\n")
    out.write("#![allow(clippy::all)]\n\n")
    out.write("use std::ffi::c_void;\nuse std::sync::atomic::AtomicUsize;\n\n")
    out.write("use super::gles::{guest_pointer, host_function};\n")
    out.write("use crate::handler;\nuse crate::runtime::{ArgSource, Handler, Ret};\n\n")
    out.write("pub fn handler(name: &str) -> Option<Handler> {\n    match name {\n")
    out.write("\n".join(lines))
    out.write("\n        _ => None,\n    }\n}\n")
print(f"generated {len(names)} GL handlers", file=sys.stderr)
